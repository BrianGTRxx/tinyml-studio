"""C del buffer de ventana (ring buffer) para la 1D-CNN y su verificación en PC."""

from __future__ import annotations

import re
import shutil
import subprocess
from pathlib import Path
from typing import Any

from tinyml_studio.i18n import tr

from .spec import DeviceSpec

WINDOW_H = """#ifndef TM_WINDOW_H
#define TM_WINDOW_H
#include "model_config.h"
#ifdef __cplusplus
extern "C" {
#endif
/* Sliding window of TM_WINDOW samples already cleaned/encoded (tm_prepare). */
void tm_window_reset(void);
/* Adds a RAW sample (num[TM_N_NUM], cat[TM_N_CAT]); drops the oldest one when full. */
void tm_window_push(const float *num, const int *cat);
/* 1 once TM_WINDOW consecutive samples are available. */
int tm_window_ready(void);
/* Copies TM_WINDOW*TM_N_FEATURES floats, from the oldest sample to the newest (row-major),
   the model input order (1, TM_WINDOW, TM_N_FEATURES). */
void tm_window_get(float *out);
#ifdef __cplusplus
}
#endif
#endif
"""

WINDOW_C = """/* Generated by TinyML Studio. */
#include <string.h>
#include "tm_window.h"
#include "tm_prepare.h"

static float tm_ring[TM_WINDOW][TM_N_FEATURES];
static int tm_head = 0;
static int tm_count = 0;

void tm_window_reset(void) { tm_head = 0; tm_count = 0; }

void tm_window_push(const float *num, const int *cat) {
  tm_prepare(num, cat, tm_ring[tm_head]);
  tm_head = (tm_head + 1) % TM_WINDOW;
  if (tm_count < TM_WINDOW) tm_count++;
}

int tm_window_ready(void) { return tm_count >= TM_WINDOW; }

void tm_window_get(float *out) {
  int start = (tm_count < TM_WINDOW) ? 0 : tm_head;
  for (int i = 0; i < TM_WINDOW; i++)
    memcpy(out + i * TM_N_FEATURES, tm_ring[(start + i) % TM_WINDOW],
           sizeof(float) * TM_N_FEATURES);
}
"""

VERIFY_WINDOW_C = r"""/* Host (PC) verification of the window buffer + tm_prepare.
   Build: cc -O2 tm_prepare.c tm_window.c verify_window_host.c -lm -o verify_window
   Run: ./verify_window test_vectors.csv */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "tm_window.h"
#include "tm_prepare.h"

#define MAXLINE 1048576
int main(int argc, char **argv) {
  if (argc < 2) { fprintf(stderr, "usage: verify_window test_vectors.csv\n"); return 2; }
  FILE *fp = fopen(argv[1], "r");
  if (!fp) { perror("csv"); return 2; }
  static char line[MAXLINE];
  float num[TM_N_NUM > 0 ? TM_N_NUM : 1];
  int cat[TM_N_CAT > 0 ? TM_N_CAT : 1];
  static float exp_w[TM_WINDOW * TM_N_FEATURES], got[TM_WINDOW * TM_N_FEATURES];
  long n = 0, ready_ok = 0;
  double maxrel = 0.0;
  if (!fgets(line, MAXLINE, fp)) return 2;
  while (fgets(line, MAXLINE, fp)) {
    char *tok = strtok(line, ",\n");
    tm_window_reset();
    int early = tm_window_ready();
    for (int j = 0; j < TM_WINDOW; j++) {
      for (int k = 0; k < TM_N_NUM && tok; k++) {
        num[k] = strtof(tok, NULL);
        tok = strtok(NULL, ",\n");
      }
      for (int k = 0; k < TM_N_CAT && tok; k++) {
        cat[k] = atoi(tok);
        tok = strtok(NULL, ",\n");
      }
      tm_window_push(num, cat);
    }
    for (int k = 0; k < TM_WINDOW * TM_N_FEATURES && tok; k++) {
      exp_w[k] = strtof(tok, NULL); tok = strtok(NULL, ",\n");
    }
    if (tm_window_ready() && !early) ready_ok++;
    tm_window_get(got);
    for (int k = 0; k < TM_WINDOW * TM_N_FEATURES; k++) {
      double d = fabs((double)got[k] - (double)exp_w[k]);
      double s = fabs((double)exp_w[k]); if (s < 1.0) s = 1.0;
      if (d / s > maxrel) maxrel = d / s;
    }
    n++;
  }
  fclose(fp);
  printf("VERIFYWIN n=%ld maxrel=%.3g ready_ok=%ld\n", n, maxrel, ready_ok);
  return 0;
}
"""


def write_window_c(out: Path, spec: DeviceSpec, cc: str = "cc") -> dict[str, Any]:
    (out / "tm_window.h").write_text(WINDOW_H, encoding="utf-8")
    (out / "tm_window.c").write_text(WINDOW_C, encoding="utf-8")
    (out / "verify_window_host.c").write_text(VERIFY_WINDOW_C, encoding="utf-8")
    if shutil.which(cc) is None:
        return {
            "available": False,
            "reason": tr("no hay compilador '{cc}'", "no compiler '{cc}'", cc=cc),
        }
    exe = out / "verify_window"
    c = subprocess.run(
        [
            cc,
            "-std=c99",
            "-O2",
            "-Wall",
            "-Wextra",
            "tm_prepare.c",
            "tm_window.c",
            "verify_window_host.c",
            "-lm",
            "-o",
            exe.name,
        ],
        cwd=out,
        capture_output=True,
        text=True,
        timeout=300,
    )
    res: dict[str, Any] = {
        "available": True,
        "compile_ok": c.returncode == 0,
        "compile_warnings": [ln for ln in c.stderr.splitlines() if "warning" in ln],
    }
    if c.returncode != 0:
        res["compile_error"] = c.stderr[-1500:]
        return res
    r = subprocess.run(
        [str(exe), "test_vectors.csv"], cwd=out, capture_output=True, text=True, timeout=300
    )
    exe.unlink(missing_ok=True)
    m = re.search(r"VERIFYWIN n=(\d+) maxrel=(\S+) ready_ok=(\d+)", r.stdout)
    if r.returncode != 0 or not m:
        res["run_error"] = (r.stderr or r.stdout)[-800:]
        return res
    res.update(
        windows=int(m[1]), features_max_rel_diff=float(m[2]), ready_flag_ok=int(m[3]) == int(m[1])
    )
    return res
